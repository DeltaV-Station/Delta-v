using Content.Shared._DV.Objectives.Eui;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._DV.Objectives.Eui;

[GenerateTypedNameReferences]
public sealed partial class ObjectiveContainer : BoxContainer
{
    private readonly SpriteSystem _sprite;
    private const int MaxTabTitleLength = 15;
    private bool _hasChanges = false;
    private readonly int _index;
    private readonly ObjectiveData _objective;
    private readonly string _originalIssuer;
    private readonly string _originalTitle;
    private readonly string _originalDesc;
    public event Action<ObjectiveData>? DeleteAction;

    public event Action<int, string>? UpdateTitleAction;

    public ObjectiveContainer(int index, ObjectiveData objective, SpriteSystem sprite)
    {
        RobustXamlLoader.Load(this);

        _sprite = sprite;

        _index = index;
        _objective = objective;

        _originalIssuer = objective.Issuer;
        _originalTitle = objective.Info.Title;
        _originalDesc = objective.Info.Description;

        ObjectiveIssuer.Text = _objective.Issuer;
        ObjectiveIssuer.OnTextChanged += OnIssuerChanged;

        ObjectiveTitle.Text = _objective.Info.Title;
        ObjectiveTitle.OnTextChanged += OnTitleChanged;

        ObjectiveDescription.TextRope = new Rope.Leaf(_objective.Info.Description);
        ObjectiveDescription.OnTextChanged += OnDescriptionChanged;
        ObjectiveDescription.Placeholder = new Rope.Leaf(Loc.GetString("objective-editor-admin-ui-placeholder-description"));

        DeleteButton.OnPressed += _ => DeleteAction?.Invoke(_objective);
        ResetButton.OnPressed += _ => ResetObjective();

        SetIcon();
        IconSelectButton.OnPressed += _ => OpenIconSelect();
    }

    public ObjectiveData GetData()
    {
        return _objective;
    }

    public void ResetObjective()
    {
        ObjectiveIssuer.Text = _originalIssuer;
        ObjectiveTitle.Text = _originalTitle;
        ObjectiveDescription.TextRope = new Rope.Leaf(_originalDesc);

        _hasChanges = false;
        UpdateTitleText();
    }

    public void UpdateTitleText()
    {
        var title = _objective.Info.Title.Length <= MaxTabTitleLength
            ? _objective.Info.Title
            : $"{_objective.Info.Title[..(MaxTabTitleLength - 3)]}...";

        if (_hasChanges)
        {
            title = "(*) " + title;
        }

        UpdateTitleAction?.Invoke(_index, title);
    }

    private void OnTitleChanged(LineEdit.LineEditEventArgs args)
    {
        _objective.Info.Title = args.Text;
        _hasChanges = true;
        UpdateTitleText();
    }

    private void OnIssuerChanged(LineEdit.LineEditEventArgs args)
    {
        _objective.Issuer = args.Text;
        _hasChanges = true;
    }

    private void OnDescriptionChanged(TextEdit.TextEditEventArgs args)
    {
        _objective.Info.Description = Rope.Collapse(args.TextRope).Trim();
        _hasChanges = true;
    }

    private void SetIcon()
    {
        // TODO(Barry): Default should probably be -> "/Textures/Interface/Nano/cross.svg.png"
        IconSelectButton.TextureNormal = _sprite.Frame0(_objective.Info.Icon);
    }

    private void OpenIconSelect()
    {

    }
}
