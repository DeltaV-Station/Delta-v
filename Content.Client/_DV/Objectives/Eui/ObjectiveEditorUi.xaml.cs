using Content.Client.UserInterface.Controls;
using Content.Shared._DV.Objectives.Eui;
using Content.Shared.Mind;
using Content.Shared.Objectives;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._DV.Objectives.Eui;

[GenerateTypedNameReferences]
public sealed partial class ObjectiveEditorUi : FancyWindow
{
    private List<ObjectiveData> _objectives = new();
    private readonly SpriteSystem _sprite;

    public ObjectiveEditorUi()
    {
        var entMan = IoCManager.Resolve<IEntityManager>();
        _sprite = entMan.System<SpriteSystem>();

        RobustXamlLoader.Load(this);
        NewObjectiveButton.OnPressed += _ => AddNewObjective();
        DeleteAllButton.OnPressed += _ => ObjectiveContainer.RemoveAllChildren();
        ResetButton.OnPressed += _ => ResetAllObjectives();
    }

    public List<ObjectiveData> GetObjectives()
    {
        var objectives = new List<ObjectiveData>();
        foreach (var child in ObjectiveContainer.Children)
        {
            if (child is not ObjectiveContainer objective)
                continue;

            objectives.Add(objective.GetData());
        }

        return objectives;
    }

    public void SetRoleDescription(ProtoId<RoleTypePrototype>? role, LocId? subtype)
    {
        var roleText = role.HasValue ? role.Value.Id.ToString() : "N/A";
        if (subtype.HasValue)
        {
            roleText += string.Format(" - {0}", Loc.GetString(subtype));
        }

        Title = Loc.GetString("objective-editor-admin-ui-title-filled", ("name", "The Admin"), ("role", roleText));
    }

    public void SetObjectives(List<ObjectiveData> data)
    {
        _objectives = data;
        ObjectiveContainer.RemoveAllChildren();

        foreach (var objective in _objectives)
        {
            AddObjectiveToUi(objective);
        }
    }

    public void ResetAllObjectives()
    {
        foreach (var child in ObjectiveContainer.Children)
        {
            if (child is not ObjectiveContainer objective)
                continue;

            objective.ResetObjective();
        }
    }

    private void AddNewObjective()
    {
        var newObjective = new ObjectiveInfo(
            Title: Loc.GetString("objective-editor-admin-ui-placeholder-title"),
            Description: Loc.GetString("objective-editor-admin-ui-placeholder-description"),
            Icon: SpriteSpecifier.Invalid, // TOOD(Barry): Probably something to think about rendering
            Progress: 0 // TODO(Barry): We need to probably do something with this
        );

        AddObjectiveToUi(
            new ObjectiveData(
                Loc.GetString("objective-editor-admin-ui-placeholder-issuer"),
                null,
                newObjective)
        );
    }

    private void AddObjectiveToUi(ObjectiveData data)
    {
        var newIndex = ObjectiveContainer.ChildCount;
        var objectiveControl = new ObjectiveContainer(newIndex, data, _sprite);

        objectiveControl.UpdateTitleAction += ObjectiveContainer.SetTabTitle;
        ObjectiveContainer.AddChild(objectiveControl);

        // Not a big fan of this, could probably do better
        // Also only seems to update when you interact with the Tab, and not as it gets written?
        objectiveControl.UpdateTitleText();
    }

    private void DeleteObjective(int index)
    {
    }
}
