using System.Diagnostics.CodeAnalysis;
using Content.Client.Guidebook.Controls;
using Content.Client.Guidebook.Richtext;
using Content.Client.Message;
using Content.Client.UserInterface.ControlExtensions;
using Content.Shared._DV.Fabricator;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._DV.Guidebook.Controls;

[GenerateTypedNameReferences]
public sealed partial class GuideFabricatorEmbed : PanelContainer, IDocumentTag, ISearchableControl, IPrototypeRepresentationControl
{
    [Dependency] private readonly IPrototypeManager _prototype = default!;

    public IPrototype? RepresentedPrototype { get; private set; }

    public GuideFabricatorEmbed()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        MouseFilter = MouseFilterMode.Stop;
    }

    public GuideFabricatorEmbed(string recipe) : this()
    {
        GenerateControl(_prototype.Index<FabricatorRecipePrototype>(recipe));
    }

    public GuideFabricatorEmbed(FabricatorRecipePrototype recipe) : this()
    {
        GenerateControl(recipe);
    }

    public void SetHiddenState(bool state, string query)
    {
        Visible = CheckMatchesSearch(query) ? state : !state;
    }

    public bool TryParseTag(Dictionary<string, string> args, [NotNullWhen(true)] out Control? control)
    {
        control = null;
        if (!args.TryGetValue("Recipe", out var id))
            return false;

        if (!_prototype.TryIndex<FabricatorRecipePrototype>(id, out var recipe))
            return false;

        GenerateControl(recipe);

        control = this;
        return true;
    }

    public bool CheckMatchesSearch(string query)
    {
        return this.ChildrenContainText(query);
    }

    private void GenerateHeader(FabricatorRecipePrototype recipe)
    {
        var entity = _prototype.Index(recipe.Result);
        RepresentedPrototype = entity;

        IconContainer.AddChild(new GuideEntityEmbed(recipe.Result, false, false));
        ResultName.SetMarkup(entity.Name);
        ResultDescription.SetMarkup(entity.Description);
    }

    private void GenerateSolidIngredients(FabricatorRecipePrototype recipe)
    {
        foreach (var (ingredient, count) in recipe.Solids)
        {
            var proto = _prototype.Index(ingredient);

            IngredientsList.AddChild(new GuideEntityEmbed(ingredient, false, false));

            AddSolid(proto, proto.Name, count);
        }
    }

    private void GenerateMaterialIngredients(FabricatorRecipePrototype recipe)
    {
        foreach (var (ingredient, count) in recipe.Materials)
        {
            var proto = _prototype.Index(ingredient);

            var name = proto.Name;
            var stackCount = count;

            var stackEnt = proto.StackEntity;
            if (_prototype.TryIndex(stackEnt, out var stack))
            {
                IngredientsList.AddChild(new GuideEntityEmbed(stack.ID, false, false));
                name = stack.Name;
                stackCount /= 100; // TODO change this value per item proto?
            }

            AddSolid(proto, name, stackCount);
        }
    }

    private void AddSolid(IPrototype proto, string name, int stack)
    {
        var msg = new FormattedMessage();
        msg.AddMarkupOrThrow(Loc.GetString("guidebook-fabricator-solid-name", ("name", name)));

        if (stack> 1)
        {
            msg.AddMarkupOrThrow(" " + Loc.GetString("guidebook-fabricator-solid-count", ("count", stack)));
        }

        var label = new GuidebookRichPrototypeLink();
        label.SetMessage(msg);
        label.LinkedPrototype = proto;

        IngredientsList.AddChild(label);
    }

    private void GenerateReagentIngredients(FabricatorRecipePrototype recipe)
    {
        foreach (var (ingredient, count) in recipe.Reagents)
        {
            var proto = _prototype.Index(ingredient);

            var msg = new FormattedMessage();
            msg.AddMarkupOrThrow(Loc.GetString("guidebook-fabricator-reagent-label",
                ("name", proto.LocalizedName), ("color", proto.SubstanceColor), ("count", count)));

            var label = new GuidebookRichPrototypeLink();
            label.SetMessage(msg);
            label.LinkedPrototype = proto;

            ReagentsList.AddChild(label);
        }
    }

    private void GenerateControl(FabricatorRecipePrototype recipe)
    {
        GenerateHeader(recipe);
        GenerateSolidIngredients(recipe);
        GenerateMaterialIngredients(recipe);
        GenerateReagentIngredients(recipe);
    }
}
